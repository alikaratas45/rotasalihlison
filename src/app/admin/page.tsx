'use client';

import { useForm, Controller } from 'react-hook-form';
import { z } from 'zod';
import { zodResolver } from '@hookform/resolvers/zod';
import { useState } from 'react';
import { addPlace } from '@/firebase/firestore/places-service';
import { useFirestore } from '@/firebase';
import { useToast } from '@/hooks/use-toast';

import { Button } from '@/components/ui/button';
import {
  Form,
  FormControl,
  FormDescription,
  FormField,
  FormItem,
  FormLabel,
  FormMessage,
} from '@/components/ui/form';
import { Input } from '@/components/ui/input';
import { Textarea } from '@/components/ui/textarea';
import { Select, SelectContent, SelectItem, SelectTrigger, SelectValue } from '@/components/ui/select';
import { Card, CardContent, CardDescription, CardHeader, CardTitle } from '@/components/ui/card';
import { Loader2 } from 'lucide-react';

const formSchema = z.object({
  name_tr: z.string().min(1, 'Türkçe isim gerekli.'),
  name_en: z.string().min(1, 'İngilizce isim gerekli.'),
  slug_tr: z.string().min(1, 'Türkçe link gerekli.'),
  slug_en: z.string().min(1, 'İngilizce link gerekli.'),
  description_tr: z.string().min(1, 'Türkçe açıklama gerekli.'),
  description_en: z.string().min(1, 'İngilizce açıklama gerekli.'),
  category: z.enum(['history', 'nature', 'food', 'shopping', 'poi']),
  lat: z.coerce.number().min(-90).max(90),
  lng: z.coerce.number().min(-180).max(180),
});

export default function AdminPage() {
  const firestore = useFirestore();
  const { toast } = useToast();
  const [isSubmitting, setIsSubmitting] = useState(false);

  const form = useForm<z.infer<typeof formSchema>>({
    resolver: zodResolver(formSchema),
    defaultValues: {
      name_tr: '',
      name_en: '',
      slug_tr: '',
      slug_en: '',
      description_tr: '',
      description_en: '',
      category: 'poi',
      lat: 38.48,
      lng: 28.14,
    },
  });

  async function onSubmit(values: z.infer<typeof formSchema>) {
    setIsSubmitting(true);
    const newPlace = {
      // A random ID is generated by Firestore, but we can add one for consistency if needed.
      // For now, let Firestore handle it.
      name: {
        tr: values.name_tr,
        en: values.name_en,
        fr: values.name_en, // Defaulting fr/de to en
        de: values.name_en,
      },
      slug: {
        tr: values.slug_tr,
        en: values.slug_en,
        fr: values.slug_en,
        de: values.slug_en,
      },
      description: {
        tr: values.description_tr,
        en: values.description_en,
        fr: values.description_en,
        de: values.description_en,
      },
      category: values.category,
      coordinates: {
        lat: values.lat,
        lng: values.lng,
      },
    };

    try {
      await addPlace(firestore, newPlace);
      toast({
        title: 'Başarılı!',
        description: `"${values.name_tr}" başarıyla eklendi.`,
      });
      form.reset();
    } catch (error) {
      toast({
        variant: 'destructive',
        title: 'Hata!',
        description: 'Yer eklenirken bir sorun oluştu.',
      });
    } finally {
      setIsSubmitting(false);
    }
  }

  return (
    <Card>
      <CardHeader>
        <CardTitle>Yeni Yer Ekle</CardTitle>
        <CardDescription>Formu doldurarak uygulamaya yeni bir mekan ekleyin.</CardDescription>
      </CardHeader>
      <CardContent>
        <Form {...form}>
          <form onSubmit={form.handleSubmit(onSubmit)} className="space-y-8">
            <div className="grid grid-cols-1 gap-6 md:grid-cols-2">
              <FormField control={form.control} name="name_tr" render={({ field }) => (
                <FormItem>
                  <FormLabel>İsim (Türkçe)</FormLabel>
                  <FormControl><Input {...field} /></FormControl>
                  <FormMessage />
                </FormItem>
              )}/>
              <FormField control={form.control} name="name_en" render={({ field }) => (
                <FormItem>
                  <FormLabel>İsim (İngilizce)</FormLabel>
                  <FormControl><Input {...field} /></FormControl>
                  <FormMessage />
                </FormItem>
              )}/>
            </div>
            <div className="grid grid-cols-1 gap-6 md:grid-cols-2">
               <FormField control={form.control} name="slug_tr" render={({ field }) => (
                <FormItem>
                  <FormLabel>Link (Türkçe)</FormLabel>
                  <FormControl><Input {...field} /></FormControl>
                  <FormDescription>URL'de görünecek kısım. Örn: "sardes-antik-kenti"</FormDescription>
                  <FormMessage />
                </FormItem>
              )}/>
              <FormField control={form.control} name="slug_en" render={({ field }) => (
                <FormItem>
                  <FormLabel>Link (İngilizce)</FormLabel>
                  <FormControl><Input {...field} /></FormControl>
                   <FormDescription>Örn: "sardes-ancient-city"</FormDescription>
                  <FormMessage />
                </FormItem>
              )}/>
            </div>
            <FormField control={form.control} name="description_tr" render={({ field }) => (
                <FormItem>
                  <FormLabel>Açıklama (Türkçe)</FormLabel>
                  <FormControl><Textarea rows={5} {...field} /></FormControl>
                  <FormMessage />
                </FormItem>
            )}/>
            <FormField control={form.control} name="description_en" render={({ field }) => (
                <FormItem>
                  <FormLabel>Açıklama (İngilizce)</FormLabel>
                  <FormControl><Textarea rows={5} {...field} /></FormControl>
                  <FormMessage />
                </FormItem>
            )}/>
            <div className="grid grid-cols-1 gap-6 md:grid-cols-3">
                 <FormField control={form.control} name="category" render={({ field }) => (
                    <FormItem>
                        <FormLabel>Kategori</FormLabel>
                        <Select onValueChange={field.onChange} defaultValue={field.value}>
                            <FormControl>
                                <SelectTrigger>
                                    <SelectValue placeholder="Kategori seçin" />
                                </SelectTrigger>
                            </FormControl>
                            <SelectContent>
                                <SelectItem value="history">Tarih</SelectItem>
                                <SelectItem value="nature">Doğa</SelectItem>
                                <SelectItem value="food">Lezzet</SelectItem>
                                <SelectItem value="shopping">Alışveriş</SelectItem>
                                <SelectItem value="poi">Önemli Nokta</SelectItem>
                            </SelectContent>
                        </Select>
                        <FormMessage />
                    </FormItem>
                )}/>
                <FormField control={form.control} name="lat" render={({ field }) => (
                    <FormItem>
                        <FormLabel>Latitude</FormLabel>
                        <FormControl><Input type="number" step="any" {...field} /></FormControl>
                        <FormMessage />
                    </FormItem>
                )}/>
                <FormField control={form.control} name="lng" render={({ field }) => (
                    <FormItem>
                        <FormLabel>Longitude</FormLabel>
                        <FormControl><Input type="number" step="any" {...field} /></FormControl>
                        <FormMessage />
                    </FormItem>
                )}/>
            </div>
            <Button type="submit" disabled={isSubmitting}>
                {isSubmitting && <Loader2 className="mr-2 h-4 w-4 animate-spin" />}
                Yeni Yeri Ekle
            </Button>
          </form>
        </Form>
      </CardContent>
    </Card>
  );
}
