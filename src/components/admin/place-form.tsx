'use client';

import { useForm } from 'react-hook-form';
import { zodResolver } from '@hookform/resolvers/zod';
import * as z from 'zod';
import { Button } from '@/components/ui/button';
import {
  Form,
  FormControl,
  FormDescription,
  FormField,
  FormItem,
  FormLabel,
  FormMessage,
} from '@/components/ui/form';
import { Input } from '@/components/ui/input';
import { Textarea } from '@/components/ui/textarea';
import {
  Select,
  SelectContent,
  SelectItem,
  SelectTrigger,
  SelectValue,
} from '@/components/ui/select';
import { Tabs, TabsContent, TabsList, TabsTrigger } from '@/components/ui/tabs';
import type { Place } from '@/lib/definitions';
import { useFirestore } from '@/firebase';
import { addPlace, updatePlace } from '@/firebase/firestore/place-service';
import { useToast } from '@/hooks/use-toast';
import { Loader2 } from 'lucide-react';
import { languages } from '@/lib/data/languages';


const LocalizedStringSchema = z.object({
  tr: z.string().min(1, 'Türkçe alan gereklidir.'),
  en: z.string().min(1, 'İngilizce alan gereklidir.'),
  fr: z.string().min(1, 'Fransızca alan gereklidir.'),
  de: z.string().min(1, 'Almanca alan gereklidir.'),
});

const formSchema = z.object({
  slug: LocalizedStringSchema,
  name: LocalizedStringSchema,
  description: LocalizedStringSchema,
  category: z.enum(['history', 'nature', 'food', 'shopping', 'poi']),
  coordinates: z.object({
    lat: z.coerce.number().min(-90).max(90),
    lng: z.coerce.number().min(-180).max(180),
  }),
  imageUrl: z.string().url('Geçerli bir URL girin.').optional().or(z.literal('')),
  imageHint: z.string().optional(),
});

type PlaceFormValues = z.infer<typeof formSchema>;

interface PlaceFormProps {
  place?: Place | null;
  onSuccess: () => void;
}

export function PlaceForm({ place, onSuccess }: PlaceFormProps) {
  const firestore = useFirestore();
  const { toast } = useToast();

  const defaultValues: PlaceFormValues = place
    ? {
        slug: place.slug,
        name: place.name,
        description: place.description,
        category: place.category,
        coordinates: place.coordinates,
        imageUrl: place.imageUrl || '',
        imageHint: place.imageHint || '',
      }
    : {
        slug: { tr: '', en: '', fr: '', de: '' },
        name: { tr: '', en: '', fr: '', de: '' },
        description: { tr: '', en: '', fr: '', de: '' },
        category: 'history',
        coordinates: { lat: 0, lng: 0 },
        imageUrl: '',
        imageHint: '',
      };

  const form = useForm<PlaceFormValues>({
    resolver: zodResolver(formSchema),
    defaultValues,
  });
  
  const { isSubmitting } = form.formState;

  async function onSubmit(values: PlaceFormValues) {
    try {
      if (place) {
        updatePlace(firestore, place.id, values);
        toast({
          title: 'Başarılı',
          description: 'Yer başarıyla güncellendi.',
        });
      } else {
        // We omit 'id' as it's generated by Firestore
        addPlace(firestore, values);
        toast({
          title: 'Başarılı',
          description: 'Yeni yer başarıyla eklendi.',
        });
      }
      onSuccess();
    } catch (error) {
      console.error("Form submission error:", error);
      toast({
        variant: 'destructive',
        title: 'Hata',
        description: 'İşlem sırasında bir hata oluştu.',
      });
    }
  }

  return (
    <Form {...form}>
      <form onSubmit={form.handleSubmit(onSubmit)} className="space-y-8">
        <Tabs defaultValue="tr" className="w-full">
          <TabsList className="grid w-full grid-cols-4">
            {languages.map(lang => (
                 <TabsTrigger key={lang.code} value={lang.code}>{lang.name}</TabsTrigger>
            ))}
          </TabsList>
            {languages.map(lang => (
            <TabsContent key={lang.code} value={lang.code} className="space-y-4 pt-4">
                <FormField
                    control={form.control}
                    name={`name.${lang.code}`}
                    render={({ field }) => (
                    <FormItem>
                        <FormLabel>Yer Adı ({lang.name})</FormLabel>
                        <FormControl>
                        <Input placeholder="Örn: Sardes Antik Kenti" {...field} />
                        </FormControl>
                        <FormMessage />
                    </FormItem>
                    )}
                />
                <FormField
                    control={form.control}
                    name={`slug.${lang.code}`}
                    render={({ field }) => (
                    <FormItem>
                        <FormLabel>URL Uzantısı (Slug - {lang.name})</FormLabel>
                        <FormControl>
                        <Input placeholder="orn: sardes-antik-kenti" {...field} />
                        </FormControl>
                        <FormDescription>URL'de görünecek kısa ad. Sadece küçük harf, rakam ve tire kullanın.</FormDescription>
                        <FormMessage />
                    </FormItem>
                    )}
                />
                <FormField
                    control={form.control}
                    name={`description.${lang.code}`}
                    render={({ field }) => (
                    <FormItem>
                        <FormLabel>Açıklama ({lang.name})</FormLabel>
                        <FormControl>
                        <Textarea placeholder="Yer hakkında detaylı bilgi..." {...field} rows={5} />
                        </FormControl>
                        <FormMessage />
                    </FormItem>
                    )}
                />
            </TabsContent>
          ))}
        </Tabs>
        
        <div className="grid grid-cols-1 md:grid-cols-2 gap-8">
          <FormField
            control={form.control}
            name="category"
            render={({ field }) => (
              <FormItem>
                <FormLabel>Kategori</FormLabel>
                <Select onValueChange={field.onChange} defaultValue={field.value}>
                  <FormControl>
                    <SelectTrigger>
                      <SelectValue placeholder="Bir kategori seçin" />
                    </SelectTrigger>
                  </FormControl>
                  <SelectContent>
                    <SelectItem value="history">Tarih</SelectItem>
                    <SelectItem value="nature">Doğa</SelectItem>
                    <SelectItem value="food">Lezzet</SelectItem>
                    <SelectItem value="shopping">Alışveriş</SelectItem>
                    <SelectItem value="poi">Önemli Nokta</SelectItem>
                  </SelectContent>
                </Select>
                <FormMessage />
              </FormItem>
            )}
          />
        </div>

        <div className="grid grid-cols-1 md:grid-cols-2 gap-8">
             <FormField
                control={form.control}
                name="coordinates.lat"
                render={({ field }) => (
                <FormItem>
                    <FormLabel>Enlem (Latitude)</FormLabel>
                    <FormControl>
                    <Input type="number" placeholder="38.4884" {...field} />
                    </FormControl>
                    <FormMessage />
                </FormItem>
                )}
            />
             <FormField
                control={form.control}
                name="coordinates.lng"
                render={({ field }) => (
                <FormItem>
                    <FormLabel>Boylam (Longitude)</FormLabel>
                    <FormControl>
                    <Input type="number" placeholder="28.0402" {...field} />
                    </FormControl>
                    <FormMessage />
                </FormItem>
                )}
            />
        </div>

         <div className="grid grid-cols-1 md:grid-cols-2 gap-8">
             <FormField
                control={form.control}
                name="imageUrl"
                render={({ field }) => (
                <FormItem>
                    <FormLabel>Görsel URL</FormLabel>
                    <FormControl>
                    <Input placeholder="https://images.unsplash.com/..." {...field} />
                    </FormControl>
                    <FormDescription>Unsplash veya Picsum gibi bir kaynaktan tam URL.</FormDescription>
                    <FormMessage />
                </FormItem>
                )}
            />
             <FormField
                control={form.control}
                name="imageHint"
                render={({ field }) => (
                <FormItem>
                    <FormLabel>Görsel İpucu (AI için)</FormLabel>
                    <FormControl>
                    <Input placeholder="ancient ruins" {...field} />
                    </FormControl>
                     <FormDescription>Görseli tanımlayan 1-2 kelime (İngilizce).</FormDescription>
                    <FormMessage />
                </FormItem>
                )}
            />
        </div>


        <div className="flex justify-end">
            <Button type="submit" disabled={isSubmitting}>
              {isSubmitting && <Loader2 className="mr-2 h-4 w-4 animate-spin" />}
              {place ? 'Değişiklikleri Kaydet' : 'Yer Ekle'}
            </Button>
        </div>
      </form>
    </Form>
  );
}
